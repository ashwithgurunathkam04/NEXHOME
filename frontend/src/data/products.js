const imageBackgrounds = [
  '#ffffff',
  '#f8f6f1',
  '#f1f4f5',
  '#f5f2ec',
  '#eef2f3',
  '#faf9f6',
]

const imageScales = [
  0.92,
  0.98,
  0.88,
  0.95,
  1,
  0.9,
  0.96,
]

const createImage = (query, id, category) => {
  return `/products/${category}/${id}.jpg`
}

const createProduct = ({
  id,
  name,
  brand,
  category,
  imageQuery,
  price,
  originalPrice,
  rating,
  reviews,
  stock,
}) => {
  return {
    id,
    name,
    brand,
    category,
    price,
    originalPrice,
    rating,
    reviews,
    stock,

    image: createImage(
      imageQuery,
      id,
      category,
    ),

    imageBackground:
      imageBackgrounds[
      id % imageBackgrounds.length
      ],

    imageScale:
      imageScales[
      id % imageScales.length
      ],

    imagePosition: 'center',
  }
}

const products = []

let id = 1

const addProducts = (
  category,
  items,
) => {
  items.forEach((item) => {
    products.push(
      createProduct({
        ...item,
        id,
        category,
      }),
    )

    id += 1
  })
}

